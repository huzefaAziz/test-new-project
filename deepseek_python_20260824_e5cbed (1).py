import networkx as nx
import numpy as np
from typing import List, Tuple, Optional, Dict, Any

class HyperellipticCurve:
    """
    Represents a hyperelliptic curve C of genus g with hyperelliptic morphism π: C → P¹.
    """
    def __init__(self, g: int):
        """
        Initialize a hyperelliptic curve of genus g.
        
        Args:
            g: genus of the curve (g ≥ 2)
        """
        if g < 2:
            raise ValueError("Genus must be at least 2")
        self.g = g
        self._build_cohomology_ring()
    
    def _build_cohomology_ring(self):
        """
        Build the cohomology ring structure using networkx.
        This represents the Hodge structure of the curve.
        """
        # Create a graph representing the cohomology ring
        self.cohomology_graph = nx.DiGraph()
        
        # Add nodes for each cohomology degree
        for i in range(3):  # degrees 0, 1, 2
            dim = 1 if i != 1 else 2 * self.g
            self.cohomology_graph.add_node(f"H^{i}", dimension=dim, degree=i)
        
        # Add multiplication edges
        if self.g > 0:
            self.cohomology_graph.add_edge("H^0", "H^1", weight=self.g)
            self.cohomology_graph.add_edge("H^1", "H^2", weight=self.g)
    
    def get_genus(self) -> int:
        """Return the genus of the curve."""
        return self.g
    
    def get_hyperelliptic_divisor(self) -> np.ndarray:
        """
        Returns the hyperelliptic divisor A = π*O_P¹(1).
        Represented as a vector in the Picard group.
        """
        return np.array([1, self.g - 1])  # [degree, h^0 - 1]


class BrillNoetherLocus:
    """
    Represents W_d^r(C), the Brill-Noether locus of degree d line bundles
    with at least r+1 global sections.
    """
    def __init__(self, curve: HyperellipticCurve, d: int, r: int):
        """
        Initialize the Brill-Noether locus.
        
        Args:
            curve: Hyperelliptic curve
            d: degree (0 ≤ d ≤ g-1)
            r: rank (r ≥ 0)
        """
        self.curve = curve
        self.d = d
        self.r = r
        self.g = curve.get_genus()
        
        if not (0 <= d <= self.g - 1):
            raise ValueError(f"d must be between 0 and {self.g - 1}")
        
        self._compute_invariants()
        self._build_determinantal_variety()
    
    def _compute_invariants(self):
        """
        Compute the invariants ℓ, ℓ', b from the paper.
        ℓ = h^0(C, L), ℓ' = h^1(C, L), b = d - 2ℓ + 2
        """
        # For a generic line bundle in W_d^0
        # ℓ is roughly d - g + 1 + h^1, but we compute properly
        self.ell = self.d - self.g + 2  # typical value for Brill-Noether general
        if self.ell < 1:
            self.ell = 1
        
        self.ell_prime = self.g - self.d + self.ell - 1
        self.b = self.d - 2 * self.ell + 2
        
        # Ensure b ≥ 0 as stated in the paper
        if self.b < 0:
            # Adjust for special cases
            self.ell = (self.d + 2) // 2
            self.ell_prime = self.g - self.d + self.ell - 1
            self.b = self.d - 2 * self.ell + 2
    
    def _build_determinantal_variety(self):
        """
        Build the catalecticant determinantal variety structure.
        This is the local model for the Brill-Noether locus.
        """
        # Create a graph representing the catalecticant matrix
        self.catalecticant_graph = nx.DiGraph()
        
        # Nodes for matrix entries
        for i in range(self.ell_prime):
            for j in range(self.ell):
                node = f"z_{i+j}"
                self.catalecticant_graph.add_node(node, row=i, col=j, value=0.0)
        
        # Add edges representing catalecticant relations
        # z_{i,j} = z_{i+1,j-1} when both exist
        for i in range(self.ell_prime - 1):
            for j in range(1, self.ell):
                node1 = f"z_{i+j}"
                node2 = f"z_{i+1+j-1}"
                if node1 != node2:
                    self.catalecticant_graph.add_edge(node1, node2, 
                                                     relation="catalecticant")
        
        # Build the matrix representation
        self.catalecticant_matrix = np.zeros((self.ell_prime, self.ell))
        for i in range(self.ell_prime):
            for j in range(self.ell):
                self.catalecticant_matrix[i, j] = 0.0  # will be filled
    
    def get_minors_ideal(self, s: int) -> List[List[int]]:
        """
        Returns the ideal generated by s×s minors of the catalecticant matrix.
        
        Args:
            s: size of minors
            
        Returns:
            List of minor indices
        """
        minors = []
        from itertools import combinations
        
        if s > min(self.ell_prime, self.ell):
            return minors
        
        # Get all s×s submatrices
        for rows in combinations(range(self.ell_prime), s):
            for cols in combinations(range(self.ell), s):
                minors.append(list(rows) + list(cols))
        
        return minors
    
    def get_dimension(self) -> int:
        """Returns the expected dimension of the Brill-Noether locus."""
        # dim W_d^r = g - (r+1)(g - d + r) from Brill-Noether theory
        # For hyperelliptic curves, the dimension is m = d - 2r
        return self.d - 2 * self.r
    
    def is_nonempty(self) -> bool:
        """Check if W_d^r is nonempty using Clifford's theorem."""
        m = self.d - 2 * self.r
        return m >= 0
    
    def get_abel_jacobi_resolution(self) -> nx.DiGraph:
        """
        Construct the Abel-Jacobi resolution C^(m) → W_d^r.
        This is a semismall resolution for hyperelliptic curves.
        """
        resolution_graph = nx.DiGraph()
        m = self.d - 2 * self.r
        
        if m < 0:
            return resolution_graph
        
        # Build the symmetric product structure
        for s in range(m + 1):
            node = f"C^({s})"
            dim = s
            resolution_graph.add_node(node, dimension=dim, degree=dim)
        
        # Add edges representing the Abel-Jacobi map
        for s in range(m):
            resolution_graph.add_edge(f"C^({s})", f"C^({s+1})", 
                                     map_type="Abel-Jacobi")
        
        return resolution_graph


class HyperellipticThetaDivisor:
    """
    Special case: theta divisor Θ = W_{g-1}^0(C).
    """
    def __init__(self, curve: HyperellipticCurve):
        """
        Initialize the theta divisor of a hyperelliptic curve.
        
        Args:
            curve: Hyperelliptic curve
        """
        self.curve = curve
        self.g = curve.get_genus()
        self.locus = BrillNoetherLocus(curve, self.g - 1, 0)
        
        # Theta divisor has special properties
        self._build_secant_variety()
    
    def _build_secant_variety(self):
        """
        Build the secant variety structure.
        The theta divisor is the secant variety of the rational normal curve.
        """
        self.secant_graph = nx.Graph()
        n = 2 * self.g - 2  # degree of the rational normal curve
        
        # Add nodes for the rational normal curve
        for i in range(n + 1):
            self.secant_graph.add_node(f"P^{i}", coord=i)
        
        # Add secant lines
        for i in range(n):
            for j in range(i + 1, n + 1):
                self.secant_graph.add_edge(f"P^{i}", f"P^{j}", secant=True)
    
    def get_multiplicity(self) -> int:
        """
        Returns the multiplicity of the theta divisor at a point.
        mult_L Θ = (g-1 choose 0) for generic point.
        """
        return 1  # theta divisor has multiplicity 1 at generic points
    
    def get_log_canonical_threshold(self) -> float:
        """
        Returns the log canonical threshold of (Pic^d(C), Θ).
        For hyperelliptic theta divisors, this is 1 + (g-1)/1 = g.
        """
        return float(self.g)


class PicardVariety:
    """
    Represents Pic^d(C), the Picard variety of degree d line bundles.
    """
    def __init__(self, curve: HyperellipticCurve, d: int):
        """
        Initialize the Picard variety.
        
        Args:
            curve: Hyperelliptic curve
            d: degree
        """
        self.curve = curve
        self.d = d
        self.g = curve.get_genus()
        self._build_tangent_space()
    
    def _build_tangent_space(self):
        """
        Build the tangent space representation.
        T_L Pic^d(C) ≅ H^1(C, O_C)
        """
        self.tangent_graph = nx.DiGraph()
        
        # Add nodes for H^1(C, O_C)
        for i in range(self.g):
            self.tangent_graph.add_node(f"e_{i}", basis=True)
        
        # Add multiplication structure
        for i in range(self.g):
            for j in range(self.g):
                # Serre duality pairing
                self.tangent_graph.add_edge(f"e_{i}", f"e_{j}", 
                                           pairing=self._serre_pairing(i, j))
    
    def _serre_pairing(self, i: int, j: int) -> float:
        """Serre duality pairing on H^1(C, O_C)."""
        # Returns the pairing between H^1(C, O_C) and H^0(C, K_C)
        if i + j == self.g - 1:
            return 1.0
        return 0.0
    
    def get_principal_polarization(self) -> np.ndarray:
        """
        Returns the principal polarization θ ∈ ∧² V.
        Represented as a skew-symmetric matrix.
        """
        theta = np.zeros((2 * self.g, 2 * self.g))
        # Standard principal polarization matrix
        for i in range(self.g):
            theta[i, i + self.g] = 1
            theta[i + self.g, i] = -1
        return theta


class CohomologyRing:
    """
    Represents the cohomology ring H^*(X, Q) for a variety X.
    """
    def __init__(self, dimension: int):
        """
        Initialize the cohomology ring.
        
        Args:
            dimension: complex dimension of the variety
        """
        self.dim = dimension
        self.ring_graph = nx.DiGraph()
        self._build_ring_structure()
    
    def _build_ring_structure(self):
        """Build the ring structure as a directed graph."""
        for i in range(2 * self.dim + 1):
            self.ring_graph.add_node(f"H^{i}", degree=i)
        
        # Add cup product edges
        for i in range(2 * self.dim + 1):
            for j in range(2 * self.dim + 1 - i):
                if i + j <= 2 * self.dim:
                    self.ring_graph.add_edge(f"H^{i}", f"H^{i+j}", 
                                            cup_product=True)
    
    def get_betti_numbers(self) -> List[int]:
        """
        Returns the Betti numbers of X.
        For hyperelliptic Brill-Noether loci:
        b_k = C(2g, k) for 0 ≤ k ≤ m
        b_k = C(2g, 2m - k) for m ≤ k ≤ 2m
        """
        return [1] * (2 * self.dim + 1)  # placeholder


class HodgeStructure:
    """
    Represents the Hodge structure of a variety.
    """
    def __init__(self, hodge_numbers: List[List[int]]):
        """
        Initialize the Hodge structure.
        
        Args:
            hodge_numbers: h^{p,q} numbers
        """
        self.hodge_numbers = hodge_numbers
        self.hodge_graph = nx.DiGraph()
        self._build_hodge_graph()
    
    def _build_hodge_graph(self):
        """Build the Hodge structure as a graph."""
        for p in range(len(self.hodge_numbers)):
            for q in range(len(self.hodge_numbers[p])):
                if self.hodge_numbers[p][q] > 0:
                    self.hodge_graph.add_node(f"H^{p,q}", p=p, q=q, 
                                             dim=self.hodge_numbers[p][q])
    
    def get_hodge_numbers(self) -> List[List[int]]:
        """Return the Hodge numbers."""
        return self.hodge_numbers


def create_hyperelliptic_brill_noether_complex(g: int, d: int, r: int) -> Dict[str, Any]:
    """
    Creates the full complex of a hyperelliptic Brill-Noether locus.
    
    Args:
        g: genus of the curve
        d: degree
        r: rank
        
    Returns:
        Dictionary containing all relevant structures
    """
    curve = HyperellipticCurve(g)
    locus = BrillNoetherLocus(curve, d, r)
    picard = PicardVariety(curve, d)
    
    # Get the Abel-Jacobi resolution
    resolution = locus.get_abel_jacobi_resolution()
    
    # Build the Hodge numbers for W_d^r
    m = locus.get_dimension()
    hodge = [[0] * (m + 1) for _ in range(m + 1)]
    
    for p in range(m + 1):
        for q in range(m + 1):
            if p + q <= m:
                hodge[p][q] = comb(g, p) * comb(g, q)
            elif p + q >= m:
                hodge[p][q] = comb(g, m - p) * comb(g, m - q)
    
    hodge_structure = HodgeStructure(hodge)
    
    return {
        'curve': curve,
        'locus': locus,
        'picard': picard,
        'resolution': resolution,
        'hodge_structure': hodge_structure,
        'dimension': m
    }

def comb(n: int, k: int) -> int:
    """Binomial coefficient with boundary handling."""
    if k < 0 or k > n:
        return 0
    from math import comb as math_comb
    return math_comb(n, k)

